import { chromium } from "playwright-core";
const b = await chromium.launch({ headless:true });
const p = await (await b.newContext()).newPage();
p.on("console",m=>{if(m.type()==="error")console.log("CE:",m.text().slice(0,120))});
await p.goto("http://127.0.0.1:8642/mods.html",{waitUntil:"domcontentloaded"});
await p.waitForSelector('a[href*="play.html"]',{timeout:15000});
await p.mouse.click(8,8);
await p.waitForTimeout(800);
console.log("menu playing:", await p.evaluate(()=>window.__bgm&&!__bgm.paused));
await p.locator('a[href*="play.html"]').first().click();
await p.waitForTimeout(1500);
console.log("play page, paused:", await p.evaluate(()=>window.__bgm?__bgm.paused:"no bgm"));
await p.mouse.click(640,420);
await p.waitForTimeout(1200);
console.log("after gate click, paused:", await p.evaluate(()=>window.__bgm?__bgm.paused:"no bgm"));
await p.evaluate(()=>{location.href="mods.html"});
await p.waitForTimeout(2000);
console.log("back in menu, playing:", await p.evaluate(()=>window.__bgm&&!__bgm.paused));
await b.close();
